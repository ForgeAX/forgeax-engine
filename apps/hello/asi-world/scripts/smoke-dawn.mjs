#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Camera, CAMERA_PROJECTION_ORTHOGRAPHIC, MeshFilter, MeshRenderer } from '@forgeax/engine-render';
import { Tilemap } from '@forgeax/engine-render/authoring';
import { Transform } from '@forgeax/engine-scene';
import { createTilemapSmoke } from '../../tilemap/scripts/smoke-host.mjs';
const here=dirname(fileURLToPath(import.meta.url));
const manifest=readFileSync(resolve(here, '..', 'dist', 'shaders', 'manifest.json'),'utf8');
const host=await createTilemapSmoke(`data:application/json,${encodeURIComponent(manifest)}`);
const {world,assets}=host;
const pixels=new Uint8Array(16*16*4);for(let i=0;i<pixels.length;i+=4)pixels.set([255,0,0,255],i);
const atlas=assets.create({kind:'texture',shape:{viewDimension:'2d',extent:{width:16,height:16}},format:'rgba8unorm',colorSpace:'linear',mips:{kind:'none'},data:pixels}).unwrap();
const tileset=assets.create({kind:'tileset',atlases:[atlas],tileWidth:16,tileHeight:16,columns:1,rows:1,regions:[{x:0,y:0,width:16,height:16}],tiles:[{regionIndex:0}]}).unwrap();
const map=world.spawn({component:Transform,data:{}},{component:Tilemap,data:{tileset,cols:64,rows:64,chunkSize:16,tiles:new Uint32Array(64*64).fill(1)}}).unwrap();
world.spawn({component:Transform,data:{pos:[32,32,10]}},{component:Camera,data:{projection:CAMERA_PROJECTION_ORTHOGRAPHIC,left:-32,right:32,bottom:-32,top:32,near:0.1,far:100,antialias:0,bloom:0,tonemap:0,clearColor:[0,0,0,1]}}).unwrap();
const count=Math.max(60,Number(process.env.SMOKE_MIN_FRAMES??60)),part=Math.floor(count/3);
await host.draw(part);host.color((await host.sample([[126,130]]))[0],[1,0,0]);
for(let i=0;i<pixels.length;i+=4)pixels.set([0,0,255,255],i);assets.update(atlas,{data:pixels}).unwrap();
await host.draw(part);host.color((await host.sample([[126,130]]))[0],[0,0,1]);
const cells=world.get(map,Tilemap).unwrap().tiles;cells[31*64+31]=0;world.set(map,Tilemap,{tiles:cells}).unwrap();
await host.draw(count-2*part);host.color((await host.sample([[126,130],[122,130]]))[0],[0,0,0]);host.color((await host.sample([[122,130]]))[0],[0,0,1]);
assert.equal([...world.query({read:[MeshFilter,MeshRenderer]}).unwrap()].length,0);
await host.finish('hello-asi-world/smoke');
