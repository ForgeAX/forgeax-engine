#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MeshFilter, MeshRenderer } from '@forgeax/engine-render';
import { createTilemapSmoke } from './smoke-host.mjs';
import { buildTilemapScene } from '../src/scene.ts';
const here=dirname(fileURLToPath(import.meta.url));
const manifest=readFileSync(resolve(here, '..', 'dist', 'shaders', 'manifest.json'),'utf8');
const host=await createTilemapSmoke(`data:application/json,${encodeURIComponent(manifest)}`);
const scene=buildTilemapScene(host.world,host.assets);
const frames=Math.max(60,Number(process.env.SMOKE_MIN_FRAMES??60));
await host.draw(Math.floor(frames/2));
const before=await host.sample([[16,240],[240,16],[48,208]]);
host.color(before[0],[1,0,0]);host.color(before[1],[1,1,0]);host.color(before[2],[0,1,0]);
scene.edit();await host.draw(Math.ceil(frames/2));
const after=await host.sample([[16,240],[240,16],[48,208]]);
host.color(after[0],[0,0,0]);host.color(after[1],[1,0,0]);host.color(after[2],[0,1,0]);
assert.equal([...host.world.query({read:[MeshFilter,MeshRenderer]}).unwrap()].length,0);
await host.finish('hello-tilemap/smoke');
