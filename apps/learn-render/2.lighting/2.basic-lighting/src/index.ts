function createUvSetMesh(uv1: readonly [number, number]): MeshAsset {
  const box = createBoxGeometry(1, 1, 1);
  if (!box.ok) {
    throw new Error(
      `[learn-render 2.lighting 2.basic-lighting] UV1 witness box creation failed: ${box.error.code}`,
    );
  }
  const source = box.value;
  const vertexCount = source.vertices.length / PROCEDURAL_FLOATS_PER_VERTEX;
  const floatsPerVertex = PROCEDURAL_FLOATS_PER_VERTEX + 2;
  const vertices = new Float32Array(vertexCount * floatsPerVertex);
  const uv1Buffer = new Float32Array(vertexCount * 2);
  for (let index = 0; index < vertexCount; index++) {
    const sourceOffset = index * PROCEDURAL_FLOATS_PER_VERTEX;
    const destinationOffset = index * floatsPerVertex;
    vertices.set(
      source.vertices.subarray(sourceOffset, sourceOffset + PROCEDURAL_FLOATS_PER_VERTEX),
      destinationOffset,
    );
    vertices[destinationOffset + PROCEDURAL_FLOATS_PER_VERTEX] = uv1[0];
    vertices[destinationOffset + PROCEDURAL_FLOATS_PER_VERTEX + 1] = uv1[1];
    uv1Buffer[index * 2] = uv1[0];
    uv1Buffer[index * 2 + 1] = uv1[1];
  }
  return {
    ...source,
    vertices,
    attributes: { ...source.attributes, uv1: uv1Buffer },
  };
}


