/** Presentation projections retain the exact setters/readbacks of their existing owner forms. */
export function mountCoastControls(
  sources: readonly Form[],
  forms: Form[],
  advanced: HTMLElement,
  qualityLabel: HTMLElement,
  manualLabel: HTMLElement,
  drivingHelp: HTMLElement,
) {
  document.getElementById('quality-controls')?.append(qualityLabel);
  document.getElementById('driving-controls')?.prepend(manualLabel, drivingHelp);
  advanced.className = 'coast-advanced-forms';
  for (const [dimension, definitions] of Object.entries(controls)) {
    const parent = document.getElementById(`controls-${dimension}`);
    if (!parent) throw new Error(`Missing coast control dimension ${dimension}`);
    const initial = definitions.flatMap((definition) => {
      const source = sources.find((form) => form.title === definition.source);
      const field = source?.fields.find((field) => field.name === definition.field);
      if (!source || !field)
        throw new Error(`Missing scene control owner: ${definition.source}.${definition.field}`);
      return [{ definition, source, field }];
    });
    const decorate = (field: RuntimeFormField, definition: Control): RuntimeFormField => {
      const seconds = (rate: unknown) => (Number(rate) === 0 ? 0 : -Math.log(0.05) / Number(rate));
      const value = definition.decaySeconds ? seconds(field.value) : field.value;
      return {
        ...field,
        ...definition,
        help: [definition.help, field.help].filter(Boolean).join(' '),
        value,
        ...(definition.decaySeconds
          ? {
              read: () => seconds(field.read?.()),
              set: (value: unknown) => {
                const time = Number(value);
                if (!Number.isFinite(time) || time < 0) throw new Error('消退时间必须为非负秒数');
                if (time === 0 && field.name.includes('waveDamping'))
                  throw new Error('Free wave damping requires a positive decay rate');
                field.set(time === 0 ? 0 : -Math.log(0.05) / time);
              },
            }
          : {}),
        defaultValue: value,
      };
    };
    const fields: RuntimeFormFields = Object.assign(
      initial.map(({ field, definition }) => decorate(field, definition)),
      {
        readFields: () => {
          const observations = new Map<Form, readonly RuntimeFormField[]>();
          return initial.flatMap<RuntimeFormField>(({ source, field, definition }) => {
            let observation = observations.get(source);
            if (!observation) {
              observation = readRuntimeFormFields(source.fields);
              observations.set(source, observation);
            }
            const current = observation.find((entry) => entry.name === field.name);
            return current
              ? [
                  {
                    ...decorate(current, definition),
                    defaultValue: decorate(field, definition).value,
                  },
                ]
              : [
                  {
                    ...decorate(field, definition),
                    readonly: true,
                    help: '当前配置没有此参数分支；恢复支持的配方后可调。',
                  },
                ];
          });
        },
      },
    );
    const form = runtimeForm(parent, '常用调控', fields);
    form.section.className = 'coast-primary-fields';
    form.section.open = true;
    forms.push(form);
  }
  for (const link of document.querySelectorAll<HTMLAnchorElement>('.dimension-nav a')) {
    link.addEventListener('click', (event) => {
      const target = document.getElementById(link.hash.slice(1));
      if (!(target instanceof HTMLDetailsElement)) return;
      event.preventDefault();
      target.open = true;
      target.scrollIntoView({ block: 'start' });
    });
  }
}
