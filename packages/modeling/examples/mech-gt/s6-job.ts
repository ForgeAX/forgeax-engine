import { generatePackMeshLods } from '@forgeax/engine-import/mesh-lod-generator';
import { type AssetsJob, bakeSources, createBakeCooker } from '@forgeax/engine-modeling';
import { AssetGuid } from '@forgeax/engine-pack/source';
import { Materials } from '@forgeax/engine-render';
import { type Asset, ok, type TextureAsset } from '@forgeax/engine-types';
import { buildS6, buildS6Detail, S6_GROUPS, S6_LODS, S6_NORMALS, type S6Group, s6Bake, s6Materials } from './s6-exterior.ts';
import outputs from './s6.outputs.json' with { type: 'json' };

/**
 * One S6 exterior group as a `modeling-mesh-job` assets job: `mesh/s6-<group>` with its LOD
 * levels, one Standard material per slot it uses, their generated textures and the baked
 * normal/AO maps. The group takes seconds to build and bake, beyond the Pack build budget
 * under load, so its Pack (s6Pack) publishes these outputs as cook sources and a build
 * plugin cooks them with `createMeshJobCooker([...S6_JOBS])` (one build per group).
 */
/**
 * Work units of one group bake (the default 2e8 guards a Pack build; a group atlas of up to
 * 2304 texels square with 32 AO rays per texel needs more).
 */
const BAKE_BUDGET = 2e10;

function s6Job(group: S6Group): AssetsJob<Record<string, never>> {
  return {
    kind: 'assets',
    name: `mech-gt.s6-${group}`,
    build: async (_params, { packageId, cache }) => {
      const guid = (key: string) => AssetGuid.format(AssetGuid.derive(packageId, key));
      const key = `s6-${group}`;
      const m = buildS6(group);
      const slots = m.inspect().materials;
      const finished = m.finish({ key, normals: S6_NORMALS });
      if (!finished.ok) return finished;
      const out: Record<string, Asset> = {};
      // Normal and AO maps on the group atlas, through the same bake cooker a Pack's deferred bake uses.
      const baked = bakeSources({ base: m, detail: buildS6Detail(group, m), ...s6Bake(group), key });
      if (!baked.ok) return baked;
      const bake = createBakeCooker({ budget: BAKE_BUDGET });
      for (const [output, entry] of Object.entries(baked.value)) {
        out[output] = (await bake.cook({ guid: guid(output), source: entry.source }, cache === undefined ? {} : { cache })).payload;
      }
      const texture = (name: string, asset: TextureAsset) => {
        out[`texture/${name}`] = asset;
        return guid(`texture/${name}`);
      };
      const ao = { texture: guid(`texture/${key}-ao`) };
      const normal = { texture: guid(`texture/${key}-normal`) };
      for (const [slot, recipe] of Object.entries(s6Materials())) {
        if (!slots.includes(slot)) continue;
        const options = recipe(texture);
        out[`material/${slot}`] = Materials.standard({ ...options, occlusionTexture: ao, ...(slot === 'louvre' && s6Bake(group).maps.includes('normal') ? { normalTexture: normal, normalScale: [1, 1] } : {}) } as typeof options);
      }
      const lods = await generatePackMeshLods(packageId, finished.value, { [`mesh/${key}`]: S6_LODS });
      if (!lods.ok) return lods;
      // Finished meshes in, finished meshes out: the LOD outputs are assets, not Pack sources.
      for (const [output, asset] of Object.entries(lods.value.outputs)) out[output] = asset as Asset;
      return ok(out);
    },
  };
}

/** The S6 group jobs, for the project's `createMeshJobCooker([...])` (with S7_JOB: one cooker key). */
export const S6_JOBS: readonly AssetsJob<Record<string, never>>[] = (Object.keys(S6_GROUPS) as S6Group[]).map(s6Job);

/** Output keys per group (regenerated by the s6-job test with FORGEAX_UPDATE_GOLDEN=1). */
export const S6_OUTPUTS: Readonly<Record<S6Group, readonly string[]>> = outputs as Record<S6Group, readonly string[]>;

export function s6JobOf(group: S6Group): AssetsJob<Record<string, never>> {
  return S6_JOBS.find((j) => j.name === `mech-gt.s6-${group}`) as AssetsJob<Record<string, never>>;
}
