import type { RigJob } from '@forgeax/engine-modeling';
import outputs from './s7.outputs.json' with { type: 'json' };
import { buildS7, TIMING } from './s7-motion.ts';

/** S7 job parameters: the Pack's `sheet` and `roundTrip` switches as booleans. */
export interface S7JobParameters {
  readonly sheet: boolean;
  readonly roundTrip: boolean;
}

/**
 * The S7 transformation rig as a `modeling-mesh-job` rig job: the Pack publishes its
 * outputs (s7.outputs.json) as cook sources and a build plugin cooks them with
 * `createMeshJobCooker([S7_JOB])` (one rig build for all of them), so the Pack build stays
 * inside its time budget.
 */
export const S7_JOB: RigJob<S7JobParameters> = {
  kind: 'rig',
  name: 'mech-gt.s7',
  build: (p) => {
    const s7 = buildS7(p.sheet ? 'sheet' : 'closed');
    return {
      rig: s7.rig,
      finish: p.roundTrip
        ? { path: s7.roundTrip, duration: 2 * TIMING.run + TIMING.hold }
        : { path: s7.forward, duration: TIMING.run },
    };
  },
};

/** Output keys of `S7_JOB` (key `s7`), regenerated by the S7 unit test with FORGEAX_UPDATE_GOLDEN=1. */
export const S7_OUTPUTS: readonly string[] = outputs;
