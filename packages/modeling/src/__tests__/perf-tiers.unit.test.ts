import { readFileSync, writeFileSync } from 'node:fs';
import { cpus, loadavg } from 'node:os';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  type CaseTiming,
  calibrationMs,
  GATE_CLOCK,
  type GatedCase,
  gatedP90,
  LOAD_SCALE_CAP,
  loadScale,
  measureCase,
  measureGated,
  overBudget,
  PERF_CASES,
  type PerfCase,
} from '../../bench/perf-tiers';
import { checkInvariants } from '../invariants';

const REPORT = new URL('../../reports/perf-tiers.json', import.meta.url);
const SUMMARY = new URL('../../reports/perf-tiers.md', import.meta.url);
const RUNTIME_RUNS = 20;
const OFFLINE_RUNS = 3;
/** A case over its budget is measured again (a shared host loaded for a moment); the best p90 counts. */
const ATTEMPTS = 3;

function measure(c: PerfCase, reference: number): GatedCase {
  const once = () =>
    c.tier === 'runtime' ? measureCase(c, RUNTIME_RUNS, 3) : measureCase(c, OFFLINE_RUNS, 0);
  return measureGated(reference, once, ATTEMPTS);
}

function summary(host: Readonly<Record<string, unknown>>, timings: readonly CaseTiming[]): string {
  const ms = (x: number) => x.toFixed(1);
  const heaviest = (t: CaseTiming) =>
    [...t.ops]
      .sort((a, b) => b.medianMs - a.medianMs)
      .slice(0, 2)
      .map((o) => `${o.op} ${ms(o.medianMs)}`)
      .join(', ');
  const rows = timings.map(
    (t) =>
      `| ${t.tier} | ${t.name} | ${t.faces} | ${t.triangles} | ${ms(t.medianMs)} | ${ms(t.p90Ms)} | ${ms(t.cpuP90Ms)} | ${t.budgetMs} | ${ms(t.finishMedianMs)} | ${heaviest(t)} |`,
  );
  return [
    '# Modeling performance tiers',
    '',
    '> [!NOTE]',
    '> Generated by `src/__tests__/perf-tiers.unit.test.ts` with `FORGEAX_UPDATE_GOLDEN=1`; cases in `bench/perf-tiers.ts`, data in `perf-tiers.json`. Times depend on the host and its load; the gate compares one p90 per case with the absolute tier budget times a load factor (1 on a host as quiet as the one that wrote `calibrationMs`, half of the calibration slowdown above that, at most 3, from a fixed same-process workload, the median of three runs taken immediately before and after each measured case, the larger of the two counting): the CPU time of the measuring thread where Node reports it (a loaded shared host inflates it far less than wall time), wall time otherwise; the thread clock advances in scheduler ticks (a few ms), so small cases read 0 or one tick. A case over its scaled budget is measured up to three times and keeps the attempt closest to it.',
    '',
    '- **runtime**: a lightweight part rebuilt from parameters (not per frame, in a Worker); one rebuild through `finish()` within 100 ms at p90.',
    '- **offline**: Pack build and cook generation; one build within 7.5 s, half the 15 s Pack build timeout.',
    '',
    `Host: ${host.cpu}, ${host.cores} cores, Node ${host.node}, load average ${host.loadAverage} at measurement; gate clock ${GATE_CLOCK}. Invariant checks off, as in a build.`,
    '',
    '| Tier | Case | Faces | Tris | Wall median ms | Wall p90 ms | CPU p90 ms | Budget ms | finish ms | Heaviest ops (median ms) |',
    '|:--|:--|--:|--:|--:|--:|--:|--:|--:|:--|',
    ...rows,
    '',
  ].join('\n');
}

describe('performance tiers (decision 2026-10-22)', () => {
  // Runtime rebuilds do not run debugValidate after every operation; the test setup does.
  beforeAll(() => checkInvariants(false));
  afterAll(() => checkInvariants(true));

  it('keeps every runtime-adjust rebuild and offline build within its tier budget', {
    timeout: 120000,
  }, () => {
    const committed = JSON.parse(readFileSync(REPORT, 'utf8')) as {
      calibrationMs?: number;
      cases: CaseTiming[];
    };
    // Without the quiet-host reference the load factor is 1 on any host: a regenerated report
    // that lost the field once left the gate unscaled.
    expect(committed.calibrationMs).toBeGreaterThan(0);
    const reference = committed.calibrationMs ?? 0;
    const gated = PERF_CASES.map((c) => measure(c, reference));
    const timings = gated.map((g) => g.timing);
    const calibration = calibrationMs();
    const report = {
      schema: 'forgeax-modeling-perf-tiers/1',
      note: 'Times are machine- and load-dependent; the gate compares the p90 of gateClock with the absolute tier budget, not with these numbers.',
      gateClock: GATE_CLOCK,
      calibrationMs: Math.round(calibration * 10) / 10,
      host: {
        cpu: cpus()[0]?.model ?? 'unknown',
        cores: cpus().length,
        node: process.version,
        loadAverage: Math.round((loadavg()[0] ?? 0) * 10) / 10,
      },
      cases: timings,
    };
    if (process.env.FORGEAX_UPDATE_GOLDEN === '1') {
      writeFileSync(REPORT, `${JSON.stringify(report, null, 2)}\n`);
      writeFileSync(SUMMARY, summary(report.host, timings));
    }
    const over = gated
      .filter((g) => overBudget(g.timing, g.scale))
      .map(
        (g) =>
          `${g.timing.name} (${g.timing.tier}): ${GATE_CLOCK} p90 ${gatedP90(g.timing)} ms > ${g.timing.budgetMs} ms x ${g.scale.toFixed(2)}`,
      );
    expect(over).toEqual([]);
    // The committed report covers the current case set; regenerate with FORGEAX_UPDATE_GOLDEN=1.
    const shape = (cases: readonly CaseTiming[]) =>
      cases.map(({ name, tier, budgetMs, faces, triangles, ops }) => ({
        name,
        tier,
        budgetMs,
        faces,
        triangles,
        ops: ops.map((o) => o.op),
      }));
    expect(shape(committed.cases)).toEqual(shape(timings));
  });

  it('scales the absolute budgets by the load of the host, never below 1 nor above the cap', () => {
    expect(loadScale(40, 40)).toBe(1);
    expect(loadScale(40, 30)).toBe(1);
    expect(loadScale(40, 60)).toBe(1.25);
    expect(loadScale(40, 100)).toBe(1.75);
    expect(loadScale(40, 4000)).toBe(LOAD_SCALE_CAP);
    expect(loadScale(0, 60)).toBe(1);
    expect(loadScale(40, Number.NaN)).toBe(1);
  });

  it('still fails a case at twice its budget on a quiet host and passes it on a loaded one', () => {
    const timing = (p90: number): CaseTiming => ({
      name: 'case',
      tier: 'runtime',
      budgetMs: 100,
      runs: 1,
      medianMs: p90,
      p90Ms: p90,
      cpuMedianMs: p90,
      cpuP90Ms: p90,
      finishMedianMs: 0,
      faces: 0,
      triangles: 0,
      ops: [],
    });
    expect(overBudget(timing(200), loadScale(40, 40))).toBe(true);
    expect(overBudget(timing(100), loadScale(40, 40))).toBe(false);
    expect(overBudget(timing(120), loadScale(40, 60))).toBe(false);
    expect(overBudget(timing(260), loadScale(40, 60))).toBe(true);
  });

  it('fails the hinge rebuilt twice per run and passes the hinge as it is', {
    timeout: 120000,
  }, () => {
    const committed = JSON.parse(readFileSync(REPORT, 'utf8')) as { calibrationMs?: number };
    const reference = committed.calibrationMs ?? 0;
    const hinge = PERF_CASES.find((c) => c.name === 'recipe hinge') as PerfCase;
    const slowed: PerfCase = {
      ...hinge,
      build: () => {
        hinge.build();
        return hinge.build();
      },
    };
    const slow = measure(slowed, reference);
    expect(overBudget(slow.timing, slow.scale)).toBe(true);
    const normal = measure(hinge, reference);
    expect(overBudget(normal.timing, normal.scale)).toBe(false);
  });
});
