import { readFileSync, writeFileSync } from 'node:fs';
import { cpus, loadavg } from 'node:os';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  type CaseTiming,
  GATE_CLOCK,
  gatedP90,
  measureCase,
  PERF_CASES,
  type PerfCase,
} from '../../bench/perf-tiers';
import { checkInvariants } from '../invariants';

const REPORT = new URL('../../reports/perf-tiers.json', import.meta.url);
const SUMMARY = new URL('../../reports/perf-tiers.md', import.meta.url);
const RUNTIME_RUNS = 20;
const OFFLINE_RUNS = 3;
/** A case over its budget is measured again (a shared host loaded for a moment); the best p90 counts. */
const ATTEMPTS = 3;

function measure(c: PerfCase): CaseTiming {
  let best: CaseTiming | undefined;
  for (let attempt = 0; attempt < ATTEMPTS; attempt++) {
    const t =
      c.tier === 'runtime' ? measureCase(c, RUNTIME_RUNS, 3) : measureCase(c, OFFLINE_RUNS, 0);
    if (best === undefined || gatedP90(t) < gatedP90(best)) best = t;
    if (gatedP90(best) <= best.budgetMs) break;
  }
  return best as CaseTiming;
}

function summary(host: Readonly<Record<string, unknown>>, timings: readonly CaseTiming[]): string {
  const ms = (x: number) => x.toFixed(1);
  const heaviest = (t: CaseTiming) =>
    [...t.ops]
      .sort((a, b) => b.medianMs - a.medianMs)
      .slice(0, 2)
      .map((o) => `${o.op} ${ms(o.medianMs)}`)
      .join(', ');
  const rows = timings.map(
    (t) =>
      `| ${t.tier} | ${t.name} | ${t.faces} | ${t.triangles} | ${ms(t.medianMs)} | ${ms(t.p90Ms)} | ${ms(t.cpuP90Ms)} | ${t.budgetMs} | ${ms(t.finishMedianMs)} | ${heaviest(t)} |`,
  );
  return [
    '# Modeling performance tiers',
    '',
    '> [!NOTE]',
    '> Generated by `src/__tests__/perf-tiers.unit.test.ts` with `FORGEAX_UPDATE_GOLDEN=1`; cases in `bench/perf-tiers.ts`, data in `perf-tiers.json`. Times depend on the host and its load; the gate compares one p90 per case with the absolute tier budget only: the CPU time of the measuring thread where Node reports it (a loaded shared host inflates it far less than wall time), wall time otherwise; the thread clock advances in scheduler ticks (a few ms), so small cases read 0 or one tick. A case over budget is measured up to three times and keeps its best p90.',
    '',
    '- **runtime**: a lightweight part rebuilt from parameters (not per frame, in a Worker); one rebuild through `finish()` within 100 ms at p90.',
    '- **offline**: Pack build and cook generation; one build within 7.5 s, half the 15 s Pack build timeout.',
    '',
    `Host: ${host.cpu}, ${host.cores} cores, Node ${host.node}, load average ${host.loadAverage} at measurement; gate clock ${GATE_CLOCK}. Invariant checks off, as in a build.`,
    '',
    '| Tier | Case | Faces | Tris | Wall median ms | Wall p90 ms | CPU p90 ms | Budget ms | finish ms | Heaviest ops (median ms) |',
    '|:--|:--|--:|--:|--:|--:|--:|--:|--:|:--|',
    ...rows,
    '',
  ].join('\n');
}

describe('performance tiers (decision 2026-10-22)', () => {
  // Runtime rebuilds do not run debugValidate after every operation; the test setup does.
  beforeAll(() => checkInvariants(false));
  afterAll(() => checkInvariants(true));

  it('keeps every runtime-adjust rebuild and offline build within its tier budget', {
    timeout: 120000,
  }, () => {
    const timings = PERF_CASES.map(measure);
    const report = {
      schema: 'forgeax-modeling-perf-tiers/1',
      note: 'Times are machine- and load-dependent; the gate compares the p90 of gateClock with the absolute tier budget, not with these numbers.',
      gateClock: GATE_CLOCK,
      host: {
        cpu: cpus()[0]?.model ?? 'unknown',
        cores: cpus().length,
        node: process.version,
        loadAverage: Math.round((loadavg()[0] ?? 0) * 10) / 10,
      },
      cases: timings,
    };
    if (process.env.FORGEAX_UPDATE_GOLDEN === '1') {
      writeFileSync(REPORT, `${JSON.stringify(report, null, 2)}\n`);
      writeFileSync(SUMMARY, summary(report.host, timings));
    }
    const over = timings
      .filter((t) => gatedP90(t) > t.budgetMs)
      .map((t) => `${t.name} (${t.tier}): ${GATE_CLOCK} p90 ${gatedP90(t)} ms > ${t.budgetMs} ms`);
    expect(over).toEqual([]);
    // The committed report covers the current case set; regenerate with FORGEAX_UPDATE_GOLDEN=1.
    const committed = JSON.parse(readFileSync(REPORT, 'utf8')) as typeof report;
    const shape = (cases: readonly CaseTiming[]) =>
      cases.map(({ name, tier, budgetMs, faces, triangles, ops }) => ({
        name,
        tier,
        budgetMs,
        faces,
        triangles,
        ops: ops.map((o) => o.op),
      }));
    expect(shape(committed.cases)).toEqual(shape(timings));
  });
});
