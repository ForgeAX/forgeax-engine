// Runtime validation is compiled from the existing JSON schema authority at build time.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';

const root = new URL('../', import.meta.url);
const ajv = new Ajv({ strict: true, allErrors: false, code: { source: true } });
addFormats(ajv, ['uuid']);
const names = {};
for (const [name, file] of [['validateMeta', 'meta'], ['validatePack', 'pack']]) {
  const schema = JSON.parse(await readFile(new URL(`schema/${file}.schema.json`, root), 'utf8'));
  ajv.addSchema(schema);
  names[name] = schema.$id;
}
const output = new URL('src/generated/', root);
await mkdir(output, { recursive: true });
await emit(new URL('schema-validators.cjs', output),
  '// Generated by scripts/generate-validators.mjs from schema/. Do not edit.\n' + standalone(ajv, names) + '\n');
await emit(new URL('schema-validators.d.cts', output),
  "import type { ValidateFunction } from 'ajv';\nexport const validateMeta: ValidateFunction;\nexport const validatePack: ValidateFunction;\n");

async function emit(path, content) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8').catch(() => null) !== content) {
      throw new Error(`Stale generated validator: ${path.pathname}. Run the package build.`);
    }
  } else {
    await writeFile(path, content);
  }
}
