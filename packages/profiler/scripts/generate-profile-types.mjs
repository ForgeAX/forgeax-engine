import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { inspect } from 'node:util';

// Public names are API policy; field shapes and variants belong to the schema.
const names = {
  source: 'ProfileSource',
  phaseRecord: 'ProfilePhaseRecord',
  skipRecord: 'ProfileSkipRecord',
  record: 'ProfileRecord',
  completeness: 'ProfileCompleteness',
};

export function generateProfileTypes(schema) {
  function type(node, depth = 0) {
    if (node.$ref !== undefined) {
      const key = node.$ref.replace(/^#\/\$defs\//, '');
      const definition = schema.$defs[key];
      if (!node.$ref.startsWith('#/$defs/') || !Object.hasOwn(schema.$defs, key)) throw new Error(`Unsupported profile reference: ${node.$ref}`);
      return Object.hasOwn(names, key) ? names[key] : type(definition, depth);
    }
    if (Object.hasOwn(node, 'const')) return inspect(node.const, { breakLength: Infinity });
    if (node.enum !== undefined) return node.enum.map((value) => inspect(value, { breakLength: Infinity })).join(' | ');
    if (node.oneOf !== undefined) return node.oneOf.map((value) => type(value, depth)).join(' | ');
    switch (node.type) {
      case 'string': return 'string';
      case 'integer':
      case 'number': return 'number';
      case 'boolean': return 'boolean';
      case 'null': return 'null';
      case 'array': return `ReadonlyArray<${type(node.items, depth)}>`;
      case 'object': {
        if (node.additionalProperties !== false)
          throw new Error('Profile object types require an explicit closed property set');
        const required = new Set(node.required ?? []);
        return `{\n${Object.entries(node.properties).map(([key, value]) =>
          `${'  '.repeat(depth + 1)}readonly ${/^[A-Za-z_$][\w$]*$/.test(key) ? key : inspect(key)}${required.has(key) ? '' : '?'}: ${type(value, depth + 1)};`).join('\n')}\n${'  '.repeat(depth)}}`;
      }
      default: throw new Error(`Unsupported profile schema shape: ${JSON.stringify(node)}`);
    }
  }
  return [
    '// Generated by scripts/generate-profile-types.mjs. Do not edit.',
    ...Object.entries(names).map(([key, name]) => `export type ${name} = ${type(schema.$defs[key])};`),
    'export type ProfileRecordKind = ProfileRecord[\'kind\'];',
    'export type ProfileCompletenessStatus = ProfileCompleteness[\'status\'];',
    `export type ProfileCapture = ${type(schema)};`,
  ].join('\n\n') + '\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const schema = JSON.parse(readFileSync(new URL('../schema/profile-capture.schema.json', import.meta.url), 'utf8'));
  const outputPath = new URL('../src/generated/profile-capture.ts', import.meta.url);
  const output = generateProfileTypes(schema);
  if (process.argv.includes('--check')) {
    if (readFileSync(outputPath, 'utf8') !== output)
      throw new Error('Stale profile types. Run scripts/generate-profile-types.mjs.');
  } else writeFileSync(outputPath, output);
}
