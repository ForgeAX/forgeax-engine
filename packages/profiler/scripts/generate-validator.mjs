// Keep the same draft, vocabularies, options and schema while removing runtime code generation.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import AjvCoreModule from 'ajv/dist/core.js';
import AddMetaSchema2020Module from 'ajv/dist/refs/json-schema-2020-12/index.js';
import Draft2020Module from 'ajv/dist/vocabularies/draft2020.js';
import standalone from 'ajv/dist/standalone/index.js';

const root = new URL('../', import.meta.url);
const AjvCore = AjvCoreModule.default ?? AjvCoreModule;
const addMetaSchema2020 = AddMetaSchema2020Module.default ?? AddMetaSchema2020Module;
const draft2020 = Draft2020Module.default ?? Draft2020Module;
const schema = JSON.parse(await readFile(new URL('schema/profile-capture.schema.json', root), 'utf8'));
const ajv = new AjvCore({ allErrors: true, dynamicRef: true, meta: false,
  next: true, strict: true, unevaluated: true, code: { source: true } });
for (const vocabulary of draft2020) ajv.addVocabulary(vocabulary);
addMetaSchema2020.call(ajv, false);
const validate = ajv.compile(schema);
const output = new URL('src/generated/', root);
await mkdir(output, { recursive: true });
await emit(new URL('schema-validator.cjs', output),
  '// Generated by scripts/generate-validator.mjs from schema/. Do not edit.\n' + standalone(ajv, validate) + '\n');
await emit(new URL('schema-validator.d.cts', output),
  "import type { ValidateFunction } from 'ajv';\nimport type { ProfileCapture } from './profile-capture.js';\n\ndeclare const validate: ValidateFunction<ProfileCapture>;\nexport = validate;\n");

async function emit(path, content) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8').catch(() => null) !== content) {
      throw new Error(`Stale generated validator: ${path.pathname}. Run the package build.`);
    }
  } else {
    await writeFile(path, content);
  }
}
