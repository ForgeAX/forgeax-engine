/** Read accepted fixed slot membership without rebuilding one array per frame. */
class ResidualSlotRows extends FrameListBase<RenderSceneSlot> {
  constructor(
    private readonly slots: SceneSlotFrame,
    private readonly members: FrameSet,
  ) {
    super();
  }
  get length(): number {
    return this.members.size;
  }
  at(index: number): RenderSceneSlot | undefined {
    const slot = this.members.at(index);
    return slot === undefined ? undefined : this.slots.slotAt(slot);
  }
  [Symbol.iterator](): IterableIterator<RenderSceneSlot> {
    return new ProjectionIterator(this.members.borrowKeys(), (slot) => {
      const row = this.slots.slotAt(slot);
      if (row === undefined)
        throw new Error('Accepted residual membership must name a fixed Scene row');
      return row;
    });
  }
}

/** Publication/removal and availability changes update the existing residual read roster. */
class ResidualReadRoster {
  private before:
    | { slots: SceneSlotFrame; residual: FrameSet; unavailable: FrameSet; value: FrameSet }
    | undefined;
  sync(slots: SceneSlotFrame, residual: FrameSet, unavailable: FrameSet): FrameSet {
    const before = this.before;
    if (
      before !== undefined &&
      before.slots.root === slots.root &&
      before.residual === residual &&
      before.unavailable === unavailable
    )
      return before.value;
    const previous = before?.value ?? new FrameSet();
    const edits = new Map<number, boolean>();
    const changed = (slot: number) => {
      const present = residual.has(slot) && !unavailable.has(slot) && slots.versionAt(slot) !== 0;
      if (previous.has(slot) !== present) edits.set(slot, present);
    };
    if (
      before === undefined ||
      (slots !== before.slots && !slots.changesSince(before.slots, changed))
    ) {
      for (const slot of residual.borrowKeys()) changed(slot);
      if (before !== undefined)
        for (const slot of before.value.borrowKeys())
          if (!residual.has(slot)) edits.set(slot, false);
    } else {
      residual.changesSince(before.residual, changed);
      unavailable.changesSince(before.unavailable, changed);
    }
    const value = edits.size === 0 ? previous : previous.edit(edits);
    this.before = { slots, residual, unavailable, value };
    return value;
  }
}

/** Everything one view's camera admission reads for one frame. */
export interface ViewCullInput {
  readonly shared: CompositionEntry;
  /** The view's submitted history and draw addresses over the shared rows. */
  readonly projection: RenderScene;
  readonly frame: ExtractedFrame;
  readonly materials: MaterialFrame;
  readonly meshes: MeshFrame;
  readonly skin: SkinSceneFrame | undefined;
  /** Terrain, glyph or tilemap rows generated by this view's frame. */
  readonly hasGeneratedDraws: boolean;
  /** Draws the GPU-driven raster owned last primary frame, while its GPU Scene is resident. */
  readonly gpuSelection: GpuDrawSelection | undefined;
  /** The shared batch plan `render-batch-plan` accepted this frame. */
  readonly plan: () => SubmissionPlan;
  /** Draw snapshots by slot address, resolved only for the GPU lane's residual rows. */
  readonly slotDraws: () => (slot: number) => RenderableSnapshot | undefined;
}

export type ViewCullResult = ReturnType<typeof cullPersistentFrame>;

/**
 * One view's camera admission state: the classic and residual cull memos and
 * the residual roster of its GPU selection. It lives exactly as long as the
 * view's state over one shared composition.
 *
 * GPU-lane frames test only residual rows and stay uncompacted; the classic
 * lane, and frames with view-generated rows, compact the culled frame.
 */
export class ViewCull {
  private readonly residual = new ResidualRoster();
  private readonly skinResidual = new FrameIntersection();
  private readonly readable = new ResidualReadRoster();
  private readonly memo: { value: PersistentCullMemo | undefined } = { value: undefined };
  private readonly residualMemo: { value: ResidualCullMemo | undefined } = { value: undefined };

  cull(input: ViewCullInput): ViewCullResult {
    const { frame, materials, meshes, skin, projection, shared } = input;
    // Frame rank is roster rank, so a ranked candidate verifies its row
    // instead of searching the identity tree.
    const roster = projection.slotsSnapshot();
    const boundsOf = (
      snapshot: RenderableSnapshot,
      index: number,
      out: box3.Box3,
      row?: RenderSceneSlot,
    ): boolean => {
      const slot =
        sceneRow(row ?? (index >= 0 ? roster.at(index) : undefined), snapshot) ??
        projection.slotOf(snapshot);
      if (snapshot.terrainSection !== undefined || snapshot.generatedMesh !== undefined)
        return writeBounds(worldBounds(snapshot), out);
      return slot === undefined
        ? writeBounds(projection.cullingWorldBounds(snapshot), out)
        : projection.writeCullingWorldBoundsAt(slot, out, meshes, materials, skin);
    };
    const selection = input.gpuSelection;
    if (selection !== undefined && !input.hasGeneratedDraws) {
      this.memo.value = undefined;
      return cullResidualFrame(
        frame,
        materials,
        boundsOf,
        this.gpuOwnedFrame(input, selection),
        selection,
        this.residualMemo,
        { meshes, skin, unavailable: shared.unavailableSlots },
      );
    }
    this.residualMemo.value = undefined;
    return cullPersistentFrame(
      frame,
      materials,
      boundsOf,
      this.memo,
      selection === undefined ? undefined : (snapshot) => selection.ownsAll(snapshot),
      meshes,
      input.hasGeneratedDraws || shared.unavailableSlots.size > 0
        ? frame.renderables
        : shared.materialDispatch,
      shared.materialDispatch.revisionValue(),
    );
  }

  /**
   * Residual rows are unbatched geometry and members of uncovered bindings,
   * retained by the view's roster from topology and selection diffs. Slot
   * roster and plan are fixed for this frame; rows resolve by slot address.
   */
  private gpuOwnedFrame(input: ViewCullInput, selection: GpuDrawSelection): GpuOwnedFrame {
    const { shared, projection } = input;
    const slots = projection.slotsSnapshot();
    const plan = input.plan();
    const unbatched = shared.topology.unbatchedSlots;
    const dispatch = shared.materialDispatch;
    const unavailable = shared.unavailableSlots;
    const roster = this.residual;

    const rowAt = input.slotDraws();
    const skin = slots.indexedSlots('skin');
    const skinResidual = this.skinResidual;
    // One fixed residual list per selection; frame rows resolve only when read.
    let memo:
      | {
          selection: GpuDrawSelection;
          set: FrameSet;
          records?: FrameList<RenderSceneSlot>;
          rows?: FrameList<RenderableSnapshot>;
        }
      | undefined;
    const residualOf = (selection: GpuDrawSelection) => {
      if (memo?.selection === selection) return memo;
      const set = roster.sync(plan, unbatched, selection);
      memo = { selection, set };
      return memo;
    };
    const readable = this.readable;
    const recordsOf = (selection: GpuDrawSelection): FrameList<RenderSceneSlot> => {
      const residual = residualOf(selection);
      residual.records ??= new ResidualSlotRows(
        slots,
        readable.sync(slots, residual.set, unavailable),
      );
      return residual.records;
    };
    return {
      residual(selection) {
        const residual = residualOf(selection);
        residual.rows ??= new FrameProjection(recordsOf(selection), (record) => {
          const row = rowAt(record.slot);
          if (row === undefined)
            throw new Error('Accepted residual Scene rows must resolve their draw frame');
          return row;
        });
        return residual.rows;
      },
      *residualSkin() {
        if (skin === undefined) {
          for (const record of recordsOf(selection)) {
            if (record.snapshot.skinBinding === undefined) continue;
            const row = rowAt(record.slot);
            if (row !== undefined) yield row;
          }
          return;
        }
        const members = skinResidual.sync(skin, residualOf(selection).set);
        for (const slot of members.borrowKeys()) {
          if (unavailable.has(slot)) continue;
          const row = rowAt(slot);
          if (row !== undefined) yield row;
        }
      },
      residualSet: (selection) => residualOf(selection).set,
      residualSlots: recordsOf,
      displays(row) {
        const slot = slots.identitySlot(row.worldId, row.entityKey);
        return slot !== undefined && dispatch.displays(slot);
      },
      row(worldId, entity) {
        const slot = slots.identitySlot(worldId, entity);
        return slot === undefined ? undefined : rowAt(slot);
      },
      slots,
      selection,
    };
  }
}
