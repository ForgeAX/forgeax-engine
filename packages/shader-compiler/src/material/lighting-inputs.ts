import {
  type BindGroupLayoutEntry,
  type DerivedMaterialInterface,
  err,
  MATERIAL_LIGHTING_INPUT_MODULE,
  materialLightingInputBindings,
  ok,
  type Result,
} from '@forgeax/engine-types';
import type { CompileResult } from '../compile.js';
import { ShaderError } from '../errors.js';
import { MaterialSourceCatalog } from './source-catalog.js';

function invalidLightingInput(message: string): ShaderError {
  return new ShaderError({
    code: 'shader-compile-failed',
    expected:
      'the generated Engine lighting_inputs module and its schema-relative resource interface',
    message,
    hint: 'import forgeax_material::lighting_inputs; do not declare lighting bindings in project WGSL',
  });
}

/** One schema-specific Engine module; project modules cannot supply this identity. */
export function materialLightingSources(
  sources: MaterialSourceCatalog,
  derived: DerivedMaterialInterface,
): Result<MaterialSourceCatalog, ShaderError> {
  if (sources.get(MATERIAL_LIGHTING_INPUT_MODULE).ok)
    return err(invalidLightingInput('lighting_inputs is generated by the material cooker'));
  return ok(
    new MaterialSourceCatalog(
      [
        ...sources.entries(),
        {
          moduleId: MATERIAL_LIGHTING_INPUT_MODULE,
          provenance: 'engine',
          virtual: true,
          path: `<${MATERIAL_LIGHTING_INPUT_MODULE}>`,
          source: materialLightingModule(derived),
          slots: [],
        },
      ],
      sources.roots,
    ),
  );
}

export function materialLightingModule(derived: DerivedMaterialInterface): string {
  const b = materialLightingInputBindings(derived.userRegionBindingEnd);
  return `#define_import_path ${MATERIAL_LIGHTING_INPUT_MODULE}
#import forgeax_pbr::standard_lighting::{SkylightUniforms}
@group(1) @binding(${b.irradianceMap}) var irradianceMap: texture_cube<f32>;
@group(1) @binding(${b.irradianceSampler}) var irradianceSampler: sampler;
@group(1) @binding(${b.prefilterMap}) var prefilterMap: texture_2d<f32>;
@group(1) @binding(${b.prefilterSampler}) var prefilterSampler: sampler;
@group(1) @binding(${b.brdfLut}) var brdfLut: texture_2d<f32>;
@group(1) @binding(${b.skylight}) var<uniform> skylight: SkylightUniforms;
@group(1) @binding(${b.skylightPrefilterMap}) var skylightPrefilterMap: texture_2d<f32>;
`;
}

// Naga-oil decorates imported identifiers with their encoded owning module.
// Check the complete name so an authored binding at a reserved coordinate
// cannot impersonate an unused Engine input.
function importedName(name: string): string {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
  let bits = 0;
  let value = 0;
  let encoded = '';
  for (const byte of new TextEncoder().encode(MATERIAL_LIGHTING_INPUT_MODULE)) {
    value = (value << 8) | byte;
    bits += 8;
    while (bits >= 5) {
      bits -= 5;
      encoded += alphabet[(value >>> bits) & 31];
    }
  }
  if (bits > 0) encoded += alphabet[(value << (5 - bits)) & 31];
  return `${name}X_naga_oil_mod_X${encoded}X`;
}

function resourceMatches(name: string, entry: BindGroupLayoutEntry): boolean {
  if (name === 'skylight') return entry.buffer?.type === 'uniform';
  if (name.endsWith('Sampler'))
    return entry.sampler !== undefined && entry.sampler.type !== 'comparison';
  return (
    entry.texture?.viewDimension === (name === 'irradianceMap' ? 'cube' : '2d') &&
    entry.texture.multisampled !== true &&
    (entry.texture.sampleType === 'float' || entry.texture.sampleType === 'unfilterable-float')
  );
}

/** Admit only resources that the trusted generated module actually published. */
export function materialLightingResources(
  derived: DerivedMaterialInterface,
  imports: Readonly<Record<string, string>>,
  compiled: CompileResult,
): Result<ReadonlySet<number>, ShaderError> {
  const source = imports[MATERIAL_LIGHTING_INPUT_MODULE];
  if (source === undefined) return ok(new Set());
  if (source !== materialLightingModule(derived))
    return err(
      invalidLightingInput('lighting_inputs source differs from the generated schema interface'),
    );
  const bindings = materialLightingInputBindings(derived.userRegionBindingEnd);
  const admitted = new Set<number>();
  const globals = compiled.reflection.boundGlobals.filter(
    (global) => global.group === derived.group,
  );
  const group = compiled.bindings.find(
    (candidate) => candidate.label === `@group(${derived.group})`,
  );
  for (const [name, binding] of Object.entries(bindings)) {
    const global = globals.find((candidate) => candidate.binding === binding);
    if (global === undefined) continue;
    const entry = group?.entries.find((candidate) => candidate.binding === binding);
    if (global.name !== importedName(name) || entry === undefined || !resourceMatches(name, entry))
      return err(
        invalidLightingInput(
          `invalid Engine lighting resource ${name} at binding ${binding}: ${global.name}; expected ${importedName(name)}; ${JSON.stringify(entry)}`,
        ),
      );
    admitted.add(binding);
  }
  return ok(admitted);
}
