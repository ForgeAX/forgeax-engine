import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { compressZstd } from '@forgeax/engine-codec/encode';
import { serializeCookedMaterialRecord, validateCookedMaterialRecord } from '@forgeax/engine-pack';
import { createMaterialPackCooker } from '@forgeax/engine-shader-compiler';

// Compile the authored TypeScript recipe with the existing package build tool.
// Absolute external URLs preserve native ESM and the pinned Three constructors
// when the small build-only module is evaluated from memory.
const recipe = await build({
  entryPoints: [fileURLToPath(new URL('../src/build/materials.ts', import.meta.url))],
  bundle: true, write: false, format: 'esm', platform: 'node',
  plugins: [{
    name: 'native-build-imports',
    setup(build) {
      build.onResolve({ filter: /^[^./]/ }, args => args.kind === 'entry-point'
        ? undefined : { path: import.meta.resolve(args.path), external: true });
    },
  }],
});
const { cookPhysicalMaterials } = await import(`data:text/javascript;base64,${Buffer.from(recipe.outputFiles[0].text).toString('base64')}`);

const { Materials } = await import('@forgeax/engine-render');
const { withClipping } = await import('@forgeax/engine-types');
const cooker = createMaterialPackCooker([], { profile: 'webgpu-storage' });
const records = [];
for (const [family, source] of [['skinned-unlit', Materials.unlit([1, 1, 1, 1])]]) {
  console.log(`Cooking Three ${family} material`);
  const cooked = await cooker.cook({ guid: `forgeax-three-${family}`, source: withClipping(source, { planes: [] }) });
  records.push(validateCookedMaterialRecord(cooked.payload.cooked).unwrap());
}
const encoded = new TextEncoder().encode(`[${records.map(serializeCookedMaterialRecord).join(',')}]`);
const compressed = await compressZstd(encoded);
if (!compressed.ok) throw compressed.error;
const directory = new URL('../src/generated/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(
  new URL('materials.mjs', directory),
  `// Generated by scripts/build-materials.mjs. Build-time Cook output; no runtime compiler.\nexport const materialPrograms = ${JSON.stringify(Buffer.from(compressed.value).toString('base64'))};\n`,
);
console.log(`Three material publication: ${records.reduce((count, record) => count + record.programs.length, 0)} programs, ${compressed.value.byteLength} compressed bytes`);

const physical = await cookPhysicalMaterials([[], ['map'], ['clearcoatMap'], ['map', 'normalMap', 'roughnessMap', 'metalnessMap', 'clearcoatMap']]);
await writeFile(new URL('physical.mjs', directory), `// Generated native Cook output.\nexport const physicalPrograms = ${JSON.stringify(physical)};\n`);
console.log(`Three Physical publication: ${physical.length} base64 bytes`);
