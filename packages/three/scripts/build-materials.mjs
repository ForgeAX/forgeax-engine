import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const directory = new URL('../src/generated/', import.meta.url);
await mkdir(directory, { recursive: true });

async function writePublication(file, name, publication) {
  return writeFile(
    new URL(file, directory),
    `// Generated by scripts/build-materials.mjs. Built-in material publication.\nexport const ${name} = ${JSON.stringify(publication)};\n`,
  );
}

// Compile the authored TypeScript recipe with the existing package build tool.
// Absolute external URLs preserve native ESM and the pinned Three constructors
// when the small build-only module is evaluated from memory.
async function loadRecipe(source) {
  const { build } = await import('esbuild');
  const recipe = await build({
  entryPoints: [fileURLToPath(new URL(source, import.meta.url))],
  bundle: true, write: false, format: 'esm', platform: 'node',
  plugins: [{
    name: 'native-build-imports',
    setup(build) {
      build.onResolve({ filter: /^[^./]/ }, args => args.kind === 'entry-point'
        ? undefined : { path: import.meta.resolve(args.path), external: true });
    },
  }],
  });
  return import(`data:text/javascript;base64,${Buffer.from(recipe.outputFiles[0].text).toString('base64')}`);
}

async function cookUnlit(packMaterialPrograms) {
  const { validateCookedMaterialRecord } = await import('@forgeax/engine-pack');
  const { createMaterialPackCooker } = await import('@forgeax/engine-shader-compiler');
  const { Materials } = await import('@forgeax/engine-render');
  const { withClipping } = await import('@forgeax/engine-types');
  const cooker = createMaterialPackCooker([], { profile: 'webgpu-storage' });
  const family = 'skinned-unlit';
  console.log(`Cooking Three ${family} material`);
  const cooked = await cooker.cook({
    guid: `forgeax-three-${family}`,
    source: withClipping(Materials.unlit([1, 1, 1, 1]), { planes: [] }),
  });
  const record = validateCookedMaterialRecord(cooked.payload.cooked).unwrap();
  console.log(`Three material publication: ${record.programs.length} programs`);
  return packMaterialPrograms([record]);
}

const prepared = process.env.FORGEAX_THREE_PROGRAM_INPUT;
if (prepared) {
  // Import only the two public data modules from the already verified Core
  // archive. Tsup still builds the complete package with these exact strings.
  for (const [file, name] of [['materials.mjs', 'materialPrograms'], ['physical.mjs', 'physicalTemplates']]) {
    const { [name]: publication } = await import(pathToFileURL(resolve(prepared, file)).href);
    if (typeof publication !== 'string' || !publication.startsWith('KLUv/'))
      throw new Error(`Invalid prepared Three program publication: ${file}`);
    await writePublication(file, name, publication);
    console.log(`[sdk-build-inputs] reused Three ${file}`);
  }
} else {
  const { publishPhysicalTemplates } = await loadRecipe('../src/build/physical-cook.ts');
  const { packMaterialPrograms } = await loadRecipe('../src/build/program-publication.ts');
  await writePublication('materials.mjs', 'materialPrograms', await cookUnlit(packMaterialPrograms));
  const { compressZstd } = await import('@forgeax/engine-codec/encode');
  const publication = await publishPhysicalTemplates();
  const compressed = await compressZstd(Buffer.from(JSON.stringify(publication)));
  if (!compressed.ok) throw compressed.error;
  await writePublication('physical.mjs', 'physicalTemplates', Buffer.from(compressed.value).toString('base64'));
  console.log('Three Physical publication: one source closure, two template shapes');
}
