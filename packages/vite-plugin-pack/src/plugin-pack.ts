// Build retains the emitted byte body; only a requested JSON consumer decodes it.
function packBodyText(body: DevPackBody | undefined): string | undefined {
  const content = packBodyContent(body);
  return content instanceof Uint8Array ? new TextDecoder().decode(content) : content;
}

